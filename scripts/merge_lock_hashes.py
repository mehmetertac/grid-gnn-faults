"""Merge pip-compile hashes from per-platform locks into the universal requirements.lock."""

from __future__ import annotations

import re
import sys
from pathlib import Path

PKG_START = re.compile(r"^([a-zA-Z0-9][a-zA-Z0-9._-]*)==")
HASH_LINE = re.compile(r"^\s*--hash=sha256:([a-f0-9]{64})")


def parse_lock(path: Path) -> list[tuple[str, list[str], set[str], list[str]]]:
    """Return records: (spec_key, spec_lines, hashes, trailing_comments)."""
    records: list[tuple[str, list[str], set[str], list[str]]] = []
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("#") and not PKG_START.match(line):
            i += 1
            continue
        if not PKG_START.match(line):
            i += 1
            continue
        spec_lines: list[str] = [line]
        hashes: set[str] = set()
        i += 1
        while i < len(lines):
            if HASH_LINE.match(lines[i]):
                hashes.add(HASH_LINE.match(lines[i]).group(1))
                spec_lines.append(lines[i])
                i += 1
                continue
            if lines[i].strip() == "\\":
                spec_lines.append(lines[i])
                i += 1
                continue
            break
        trailing: list[str] = []
        while i < len(lines) and lines[i].strip().startswith("#"):
            trailing.append(lines[i])
            i += 1
        spec_key = spec_key_from_record(spec_lines)
        records.append((spec_key, spec_lines, hashes, trailing))
    return records


def spec_key_from_record(spec_lines: list[str]) -> str:
    parts: list[str] = []
    for line in spec_lines:
        stripped = line.strip().rstrip("\\").strip()
        if stripped.startswith("--hash") or stripped == "\\" or not stripped:
            continue
        parts.append(stripped)
    return " ".join(parts)


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    universal_path = root / "requirements.lock"
    fragments = [
        root / "requirements.win.lock",
        root / "requirements.win312.lock",
        root / "requirements.linux311.lock",
        root / "requirements.linux312.lock",
    ]
    header = (
        "# This file was autogenerated by scripts/merge_lock_hashes.py\n"
        "# Universal pins (uv pip compile --universal) with merged wheel hashes.\n"
        "# Regenerate: compile universal + per-platform locks, then run this script.\n"
    )
    universal = parse_lock(universal_path)
    hash_by_pkg: dict[str, set[str]] = {}
    for frag in fragments:
        if not frag.exists():
            print(f"skip missing {frag.name}", file=sys.stderr)
            continue
        for spec_key, _, hashes, _ in parse_lock(frag):
            pkg = spec_key.split("==", 1)[0].lower()
            hash_by_pkg.setdefault(pkg, set()).update(hashes)

    out: list[str] = [header.rstrip()]
    for spec_key, _, _, trailing in universal:
        pkg = spec_key.split("==", 1)[0].lower()
        merged = sorted(hash_by_pkg.get(pkg, set()))
        if not merged:
            print(f"warning: no fragment hashes for {spec_key}", file=sys.stderr)
            continue
        if len(merged) == 1:
            out.append(f"{spec_key} \\")
            out.append(f"    --hash=sha256:{merged[0]}")
        else:
            out.append(f"{spec_key} \\")
            for idx, h in enumerate(merged):
                suffix = " \\" if idx < len(merged) - 1 else ""
                out.append(f"    --hash=sha256:{h}{suffix}")
        out.extend(trailing)
    universal_path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {universal_path} ({len(universal)} requirement lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())